"""
data/generate_data.py — Synthetic dataset generator for RecoverAI.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
DESIGN ASSUMPTIONS PER FAILURE REASON
(These drive both the data distribution AND the hidden ground-truth labels)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

BANK_SERVER_DOWN (weight ~25%)
  - Cause: The bank's payment processor was temporarily unavailable.
  - Recovery: Very likely recoverable — it's not a customer problem.
    A retry or payment link a few hours later usually succeeds.
  - Ground truth: ~75–85% recoverable, with noise.
  - Amount distribution: full range (including some large amounts).

INSUFFICIENT_FUNDS (weight ~30%)
  - Cause: Customer's account balance was too low at time of payment.
  - Recovery: Often NOT immediately recoverable via retry — the money isn't
    there yet. However, a payment link sent 24–48 hrs later (hoping salary
    credited or funds moved) can work for loyal customers.
  - Ground truth: ~25–35% recoverable, strongly correlated with customer
    payment history (loyal customers are more likely to top up and return).
  - Amount distribution: skewed toward smaller amounts; large amounts are
    less likely to succeed if funds were insufficient.

NETWORK_TIMEOUT (weight ~20%)
  - Cause: Connection dropped mid-transaction (customer's network or
    gateway side). Payment may or may not have been deducted.
  - Recovery: High — usually just a transient glitch. Retry or resend link.
  - Ground truth: ~70–80% recoverable.
  - Amount distribution: full range.

CARD_EXPIRED (weight ~15%)
  - Cause: Customer's card reached its expiry date.
  - Recovery: NOT recoverable via retry — the card is dead. Recovery requires
    the customer to use a different payment method. A payment link (which
    lets them choose any method) can work, but only if the customer is
    motivated to pay.
  - Ground truth: ~20–30% recoverable (depends heavily on customer loyalty).

INVALID_OTP (weight ~10%)
  - Cause: Customer entered the wrong one-time password, or OTP expired
    before they entered it.
  - Recovery: Conditional — if the customer is willing to retry and enters
    the OTP correctly, it works. But repeat OTP failures suggest either
    phishing concern or a disengaged customer.
  - Ground truth: ~40–55% recoverable, drops sharply with previous_attempts.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
CIRCULAR-EVALUATION GUARD
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
The hidden `actual_recovery_outcome` in the `ground_truth` table is
generated by a SEPARATE, NOISIER function (_ground_truth_oracle) that
intentionally differs from the recovery_probability formula in diagnosis.py.

Specifically:
  - _ground_truth_oracle uses a different random seed path
  - It adds ±15% structured noise and 10% pure random exceptions
  - The base rates per failure type differ slightly from the heuristic's
    weights, so diagnosis.py cannot "cheat" by learning the exact formula

This means Phase 7 metrics (precision, recall, F1) will be genuinely
honest — the model cannot score 100% because the labels have intentional,
realistic noise.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
"""

